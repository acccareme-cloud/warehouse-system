// t('login.heading') -> يمشي جوه الكائن بالـ dot notation، ويستبدل {code} لو فيه params
export function translate(lang, key, params = {}) {
  const parts = key.split('.');
  let node = translations[lang] || translations.ar;
  for (const p of parts) {
    node = node?.[p];
    if (node === undefined) return key; // مفتاح ناقص -> رجّع المفتاح نفسه بدل ما يكسر الشاشة
  }
  if (typeof node === 'string') {
    return node.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? params[k] : `{${k}}`));
  }
  return node;
}
